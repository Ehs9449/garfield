#!/usr/bin/env python3
"""
Semantic point clouds -> closed B-rep -> EnergyPlus IDF.

This replaces the grid massing of cloud_to_idf.py. Walls now lie on the
real facade planes, so the tower stops looking like a stack of slabs and
the windows land where they belong.

Method
------
1.  Find the vertical facade planes in the envelope cloud. Each one becomes
    a straight line in plan.
2.  Build the arrangement of those lines inside the building's bounding box.
    The lines cut the plan into convex cells. This is the 2D version of the
    plane arrangement used by PolyFit, and it is small enough to solve by
    labelling instead of integer programming.
3.  Label each cell full or empty from the point occupancy, and give every
    full cell a height.
4.  Extrude. Floor under every full cell, roof on top of it, and a vertical
    wall on every arrangement edge where the height changes. Closed by
    construction, and every surface is convex.
5.  Windows are found per wall, on the wall's own plane, so one window is
    one connected patch of glazing instead of a 3D blob.
6.  Columns become shading, using the minimum rotated rectangle of each
    cluster rather than an axis-aligned box.

Usage
-----
    python brep_to_idf.py \
        --envelope "roof - Cloud.ply" \
        --windows  "window - Cloud.ply" \
        --columns  "column - Cloud.ply" \
        --height 53.0 --out lsu_tower.idf --preview massing.ply
"""

