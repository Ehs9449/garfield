CONSTRUCTION = {"Wall": "ExtWall", "Roof": "ExtRoof", "Floor": "ExtFloor"}

def load_points(path):
    if path is None or not os.path.exists(path):
        return np.zeros((0, 3))
    return np.asarray(o3d.io.read_point_cloud(path).points)

def load_many(paths):
    """Stack several clouds, e.g. --envelope wall.ply roof.ply."""
    if not paths:
        return np.zeros((0, 3))
    if isinstance(paths, str):
        paths = [paths]
    parts = [load_points(p) for p in paths]
    parts = [p for p in parts if len(p)]
    return np.vstack(parts) if parts else np.zeros((0, 3))


def point_spacing(points, sample=20000):
    """Median distance to the nearest neighbour, in the cloud's own units."""
    from scipy.spatial import cKDTree
    pick = points
    if len(points) > sample:
        pick = points[np.random.default_rng(0).choice(len(points), sample,
                                                      replace=False)]
    dist, _ = cKDTree(points).query(pick, k=2)
    return float(np.median(dist[:, 1]))


def clean_envelope(points, nb, std_ratio, eps_factor):
    """Remove the noise that the segmentation leaves around the building.

    The wall and roof clouds hold stray points on the ground, in the trees
    and far away. Those points stretch the bounding box, the height scale
    and the arrangement, so the model came out longer than the building.
    Keep only the largest connected piece of the cloud.
    """
    cloud = o3d.geometry.PointCloud()
    cloud.points = o3d.utility.Vector3dVector(points)
    cloud, _ = cloud.remove_statistical_outlier(nb_neighbors=nb,
                                                std_ratio=std_ratio)
    kept = np.asarray(cloud.points)

    spacing = point_spacing(kept)
    labels = np.array(cloud.cluster_dbscan(eps=eps_factor * spacing,
                                           min_points=10,
                                           print_progress=False))
    if labels.max() < 0:
        return kept, spacing
    sizes = np.bincount(labels[labels >= 0])
    return kept[labels == int(np.argmax(sizes))], spacing


def near_building(points, reference, distance):
    """Keep the points that lie within `distance` of the clean envelope."""
    if len(points) == 0:
        return points
    from scipy.spatial import cKDTree
    dist, _ = cKDTree(reference).query(points, k=1)
    return points[dist <= distance]


def read_directions(path):
    if path is None:
        return None
    rows = []
    with open(path) as handle:
        for line in handle:
            line = line.strip()
            if line and not line.startswith("#"):
                rows.append([float(x) for x in line.replace(",", " ").split()])
    return np.array(rows, float) if rows else None

def building_frame(directions, points):
    """Rotation whose Z is up and whose X follows the building's long axis."""
    if directions is None or len(directions) < 3:
        flat = points[:, :2] - points[:, :2].mean(axis=0)
        _, vectors = np.linalg.eigh(flat.T @ flat)
        x_axis = np.array([vectors[0, -1], vectors[1, -1], 0.0])
    else:
        unit = directions / np.linalg.norm(directions, axis=1, keepdims=True)
        up = int(np.argmax(np.abs(unit[:, 2])))
        x_axis = np.array(
            [unit[i] for i in range(len(unit)) if i != up][0], float)
        x_axis[2] = 0.0

    if np.linalg.norm(x_axis) < 1e-9:
        x_axis = np.array([1.0, 0.0, 0.0])
    if x_axis[0] < 0 or (abs(x_axis[0]) < 1e-9 and x_axis[1] < 0):
        x_axis = -x_axis                     # keep the frame canonical
    x_axis /= np.linalg.norm(x_axis)
    z_axis = np.array([0.0, 0.0, 1.0])
    y_axis = np.cross(z_axis, x_axis)
    rotation = np.vstack([x_axis, y_axis, z_axis])
    north = float(np.degrees(np.arctan2(x_axis[1], x_axis[0])))
    return rotation, north

def polygon_normal(vertices):
    normal = np.zeros(3)
    for i in range(len(vertices)):
        normal += np.cross(vertices[i], vertices[(i + 1) % len(vertices)])
    length = np.linalg.norm(normal)
    return normal / length if length else normal

def polygon_area(vertices):
    total = np.zeros(3)
    for i in range(len(vertices)):
        total += np.cross(vertices[i], vertices[(i + 1) % len(vertices)])
    return 0.5 * np.linalg.norm(total)

def orient(vertices, outward):
    """EnergyPlus wants vertices counter-clockwise seen from outside,
    starting at the upper-left corner."""
    v = list(vertices)
    if polygon_normal(v) @ outward < 0:
        v = v[::-1]

    left = np.cross(np.array([0.0, 0.0, 1.0]), outward)
    if np.linalg.norm(left) < 1e-9:
        left = np.array([1.0, 0.0, 0.0])
    left /= np.linalg.norm(left)

    keys = np.array([[-round(p[2], 4), round(float(p @ left), 4)] for p in v])
    start = int(np.lexsort((keys[:, 1], keys[:, 0]))[0])
    return v[start:] + v[:start]

def vertex_block(vertices, indent="    "):
    lines = []
    for number, point in enumerate(vertices, start=1):
        end = ";" if number == len(vertices) else ","
        lines.append(f"{indent}{point[0]:.4f}, {point[1]:.4f}, "
                     f"{point[2]:.4f}{end}  !- Vertex {number} X,Y,Z")
    return "\n".join(lines)

def write_idf(path, surfaces, windows, shades, zone, north, version, name):
    blocks = [HEADER.format(version=version, north=north, zone=zone,
                            name=name)]

    for surface in surfaces:
        kind = surface["type"]
        if kind == "Floor":
            boundary, sun, wind = "Ground", "NoSun", "NoWind"
        else:
            boundary, sun, wind = "Outdoors", "SunExposed", "WindExposed"

        blocks.append(
            "BuildingSurface:Detailed,\n"
            f"    {surface['name']},\n"
            f"    {kind},\n"
            f"    {CONSTRUCTION[kind]},\n"
            f"    {zone},\n"
            "    ,                        !- Space Name\n"
            f"    {boundary},\n"
            "    ,                        !- Outside Boundary Condition Object\n"
            f"    {sun},\n"
            f"    {wind},\n"
            "    ,                        !- View Factor to Ground\n"
            f"    {len(surface['vertices'])},  !- Number of Vertices\n"
            + vertex_block(surface["vertices"]))

    for window in windows:
        blocks.append(
            "FenestrationSurface:Detailed,\n"
            f"    {window['name']},\n"
            f"    {window.get('kind', 'Window')},\n"
            f"    {window.get('construction', 'ExtWindow')},\n"
            f"    {window['wall']},\n"
            "    ,                        !- Outside Boundary Condition Object\n"
            "    ,                        !- View Factor to Ground\n"
            "    ,                        !- Frame and Divider Name\n"
            "    1,                       !- Multiplier\n"
            "    4,                       !- Number of Vertices\n"
            + vertex_block(window["vertices"]))

    for shade in shades:
        blocks.append(
            "Shading:Building:Detailed,\n"
            f"    {shade['name']},\n"
            "    ,                        !- Transmittance Schedule Name\n"
            "    4,                       !- Number of Vertices\n"
            + vertex_block(shade["vertices"]))

    with open(path, "w") as handle:
        handle.write("\n\n".join(blocks) + "\n")

def write_preview(path, surfaces, windows, shades):
    """One coloured mesh so the result can be opened next to the cloud."""
    palette = {"Wall": [0.75, 0.75, 0.78], "Roof": [0.85, 0.30, 0.25],
               "Floor": [0.25, 0.35, 0.65], "Window": [0.20, 0.85, 0.95],
               "Column": [1.00, 0.80, 0.20], "Door": [0.45, 0.25, 0.10]}

    vertices, triangles, colours = [], [], []

    def add(polygon, colour):
        base = len(vertices)
        vertices.extend(polygon)
        colours.extend([colour] * len(polygon))
        for i in range(1, len(polygon) - 1):
            triangles.append([base, base + i, base + i + 1])

    for surface in surfaces:
        add(surface["vertices"], palette[surface["type"]])
    for window in windows:
        add(window["vertices"], palette[window.get("kind", "Window")])
    for shade in shades:
        add(shade["vertices"], palette["Column"])

    mesh = o3d.geometry.TriangleMesh()
    mesh.vertices = o3d.utility.Vector3dVector(np.array(vertices))
    mesh.triangles = o3d.utility.Vector3iVector(
        np.array(triangles, dtype=np.int32))
    mesh.vertex_colors = o3d.utility.Vector3dVector(np.array(colours))
    mesh.compute_vertex_normals()
    o3d.io.write_triangle_mesh(path, mesh)

def write_scaled_cloud(path, blocks):
    """The input clouds after rotation and scaling, for side-by-side checks."""
    points, colours = [], []
    palette = {"envelope": [0.85, 0.30, 0.25], "window": [0.20, 0.85, 0.95],
               "door": [0.45, 0.25, 0.10], "opening": [0.60, 0.20, 0.60],
               "column": [1.00, 0.80, 0.20]}
    for name, data in blocks.items():
        if len(data):
            points.append(data)
            colours.append(np.tile(palette[name], (len(data), 1)))
    if not points:
        return
    cloud = o3d.geometry.PointCloud()
    cloud.points = o3d.utility.Vector3dVector(np.vstack(points))
    cloud.colors = o3d.utility.Vector3dVector(np.vstack(colours))
    o3d.io.write_point_cloud(path, cloud)

def closure_report(surfaces):
    """Divergence theorem: a closed surface has sum(area * normal) == 0."""
    total_area = sum(s["area"] for s in surfaces)
    imbalance = np.zeros(3)
    volume = 0.0
    for s in surfaces:
        imbalance += s["area"] * s["outward"]
        centroid = np.mean(s["vertices"], axis=0)
        volume += (centroid @ s["outward"]) * s["area"] / 3.0
    return total_area, float(np.linalg.norm(imbalance)), volume


