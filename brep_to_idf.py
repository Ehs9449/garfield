def key_of(point, places=4):
    return (round(point[0], places), round(point[1], places))


def extrude(faces, inside, heights):
    """Floor, roof and walls of the labelled arrangement."""
    surfaces = []
    edges = defaultdict(list)

    for index, face in enumerate(faces):
        if not inside[index]:
            continue
        ring = list(face.exterior.coords)[:-1]
        height = heights[index]

        floor = [np.array([x, y, 0.0]) for x, y in ring]
        surfaces.append({"type": "Floor", "outward": np.array([0., 0., -1.]),
                         "vertices": orient(floor, np.array([0., 0., -1.]))})

        roof = [np.array([x, y, height]) for x, y in ring]
        surfaces.append({"type": "Roof", "outward": np.array([0., 0., 1.]),
                         "vertices": orient(roof, np.array([0., 0., 1.]))})

        for a, b in zip(ring, ring[1:] + ring[:1]):
            edges[tuple(sorted((key_of(a), key_of(b))))].append(index)

    # collect every edge of the arrangement, including the outer boundary
    for index, face in enumerate(faces):
        ring = list(face.exterior.coords)[:-1]
        for a, b in zip(ring, ring[1:] + ring[:1]):
            key = tuple(sorted((key_of(a), key_of(b))))
            if index not in edges[key]:
                edges[key].append(index)

    for (pa, pb), owners in edges.items():
        levels = []
        for index in owners:
            levels.append(heights[index] if inside[index] else 0.0)
        while len(levels) < 2:
            levels.append(0.0)
        if len(levels) > 2:
            levels = sorted(levels)[-2:]

        low, high = min(levels), max(levels)
        if high - low < 1e-6:
            continue

        tall = owners[int(np.argmax([
            heights[i] if inside[i] else 0.0 for i in owners]))]
        along = np.array([pb[0] - pa[0], pb[1] - pa[1]])
        if np.linalg.norm(along) < 1e-9:
            continue
        outward = np.array([along[1], -along[0]])
        outward /= np.linalg.norm(outward)

        middle = np.array([(pa[0] + pb[0]) / 2, (pa[1] + pb[1]) / 2])
        centre = np.array(faces[tall].centroid.coords[0])
        if outward @ (middle - centre) < 0:
            outward = -outward

        quad = [np.array([pa[0], pa[1], low]), np.array([pb[0], pb[1], low]),
                np.array([pb[0], pb[1], high]), np.array([pa[0], pa[1], high])]
        surfaces.append({"type": "Wall",
                         "outward": np.array([outward[0], outward[1], 0.0]),
                         "vertices": orient(quad, np.array([outward[0],
                                                            outward[1], 0.0]))})

    for number, surface in enumerate(surfaces, start=1):
        surface["name"] = f"{surface['type']}_{number:04d}"
        surface["area"] = polygon_area(surface["vertices"])
    return surfaces


# --------------------------------------------------------------------------
# 4. windows, found on each wall's own plane
# --------------------------------------------------------------------------

def wall_frame(surface):
    outward = surface["outward"]
    horizontal = np.cross(np.array([0.0, 0.0, 1.0]), outward)
    horizontal /= np.linalg.norm(horizontal)
    vertical = np.array([0.0, 0.0, 1.0])
    origin = surface["vertices"][0]
    a = [float((p - origin) @ horizontal) for p in surface["vertices"]]
    b = [float((p - origin) @ vertical) for p in surface["vertices"]]
    return origin, horizontal, vertical, (min(a), max(a)), (min(b), max(b))


def windows_on_walls(points, walls, band, cell, margin, min_size, min_points,
                     reach):
    """Assign each glazing point to its nearest wall, then cut it up.

    reach: slack on the wall rectangle. A wall is one arrangement edge, so a
    window sitting just past a corner would otherwise find no host.
    """
    if len(points) == 0 or not walls:
        return [], {"unassigned": 0, "unassigned_points": points}

    best = np.full(len(points), -1)
    best_distance = np.full(len(points), band)

    for index, wall in enumerate(walls):
        origin, ha, va, arange, brange = wall["frame"]
        delta = points - origin
        distance = np.abs(delta @ wall["outward"])
        a = delta @ ha
        b = delta @ va
        ok = ((distance < best_distance)
              & (a >= arange[0] - reach) & (a <= arange[1] + reach)
              & (b >= brange[0] - reach) & (b <= brange[1] + reach))
        best[ok] = index
        best_distance[ok] = distance[ok]

    windows = []
    orphans = points[best < 0]
    unassigned = int(len(orphans))

    for index, wall in enumerate(walls):
        chosen = points[best == index]
        if len(chosen) < min_points:
            continue

        origin, ha, va, arange, brange = wall["frame"]
        delta = chosen - origin
        a = delta @ ha
        b = delta @ va

        a = np.clip(a, arange[0], arange[1])
        b = np.clip(b, brange[0], brange[1])
        ia = np.floor((a - arange[0]) / cell).astype(int)
        ib = np.floor((b - brange[0]) / cell).astype(int)
        shape = (int(ia.max()) + 1, int(ib.max()) + 1)
        grid = np.zeros(shape, dtype=np.int32)
        np.add.at(grid, (ia, ib), 1)

        mask = grid >= 1
        mask = ndimage.binary_closing(mask, structure=np.ones((2, 2), bool))
        mask = ndimage.binary_fill_holes(mask)
        labels, total = ndimage.label(mask, structure=np.ones((3, 3)))

        count = 0
        for region in range(1, total + 1):
            piece = labels == region
            if grid[piece].sum() < min_points:
                continue
            ri, ci = np.nonzero(piece)
            amin = arange[0] + ri.min() * cell
            amax = arange[0] + (ri.max() + 1) * cell
            bmin = brange[0] + ci.min() * cell
            bmax = brange[0] + (ci.max() + 1) * cell

            amin = max(amin, arange[0] + margin)
            amax = min(amax, arange[1] - margin)
            bmin = max(bmin, brange[0] + margin)
            bmax = min(bmax, brange[1] - margin)
            if amax - amin < min_size or bmax - bmin < min_size:
                continue

            count += 1
            quad = [origin + ha * amin + va * bmin,
                    origin + ha * amax + va * bmin,
                    origin + ha * amax + va * bmax,
                    origin + ha * amin + va * bmax]
            windows.append({"name": f"{wall['name']}_Win_{count:02d}",
                            "wall": wall["name"],
                            "vertices": orient(quad, wall["outward"]),
                            "area": (amax - amin) * (bmax - bmin)})

    return windows, {"unassigned": unassigned, "unassigned_points": orphans}


# --------------------------------------------------------------------------
# 5. columns as shading
# --------------------------------------------------------------------------

def column_shades(points, eps, min_points, min_height, max_width,
                  min_slenderness):
    if len(points) < min_points:
        return [], {"too_short": 0, "too_wide": 0, "too_fat": 0}, []

    cloud = o3d.geometry.PointCloud()
    cloud.points = o3d.utility.Vector3dVector(points)
    labels = np.array(cloud.cluster_dbscan(eps=eps, min_points=min_points,
                                           print_progress=False))

    shades = []
    rejected = {"too_short": 0, "too_wide": 0, "too_fat": 0}
    measured = []
    kept = 0

    for group_id in range(labels.max() + 1):
        group = points[labels == group_id]
        low, high = group[:, 2].min(), group[:, 2].max()

        plan = Polygon(group[:, :2]).convex_hull.minimum_rotated_rectangle
        if plan.is_empty or plan.geom_type != "Polygon":
            rejected["too_wide"] += 1
            continue
        ring = list(plan.exterior.coords)[:-1]
        sides = [np.hypot(ring[i][0] - ring[(i + 1) % 4][0],
                          ring[i][1] - ring[(i + 1) % 4][1])
                 for i in range(4)]
        width = max(sides)
        measured.append((high - low, width, len(group)))

        if high - low < min_height:
            rejected["too_short"] += 1
            continue
        if width > max_width:
            rejected["too_wide"] += 1
            continue
        if (high - low) / max(width, 1e-6) < min_slenderness:
            rejected["too_fat"] += 1
            continue

        kept += 1
        centre = np.array(plan.centroid.coords[0])
        for side in range(4):
            pa, pb = ring[side], ring[(side + 1) % 4]
            along = np.array([pb[0] - pa[0], pb[1] - pa[1]])
            if np.linalg.norm(along) < 1e-9:
                continue
            outward = np.array([along[1], -along[0]])
            outward /= np.linalg.norm(outward)
            middle = np.array([(pa[0] + pb[0]) / 2, (pa[1] + pb[1]) / 2])
            if outward @ (middle - centre) < 0:
                outward = -outward
            quad = [np.array([pa[0], pa[1], low]),
                    np.array([pb[0], pb[1], low]),
                    np.array([pb[0], pb[1], high]),
                    np.array([pa[0], pa[1], high])]
            shades.append({
                "name": f"Column_{kept:03d}_S{side + 1}",
                "vertices": orient(quad, np.array([outward[0], outward[1],
                                                   0.0]))})
    return shades, rejected, measured


