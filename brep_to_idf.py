def estimate_normals(points, radius, max_nn=40):
    cloud = o3d.geometry.PointCloud()
    cloud.points = o3d.utility.Vector3dVector(points)
    cloud.estimate_normals(
        search_param=o3d.geometry.KDTreeSearchParamHybrid(radius=radius,
                                                          max_nn=max_nn))
    normals = np.asarray(cloud.normals)
    length = np.linalg.norm(normals, axis=1, keepdims=True)
    length[length == 0] = 1.0
    return normals / length


def facade_directions(normals, vertical_angle, bins, min_share):
    """Angles, in plan, of the facade planes. Handles non-Manhattan walls."""
    horizontal = np.abs(normals[:, 2]) < np.sin(np.deg2rad(vertical_angle))
    flat = normals[horizontal][:, :2]
    if len(flat) == 0:
        return [], horizontal

    angle = np.degrees(np.arctan2(flat[:, 1], flat[:, 0])) % 180.0
    counts, edges = np.histogram(angle, bins=bins, range=(0.0, 180.0))
    # the histogram wraps at 180 degrees
    wrapped = np.r_[counts, counts, counts].astype(float)
    smooth = ndimage.uniform_filter1d(wrapped, size=3)[bins:2 * bins]

    peaks, _ = find_peaks(np.r_[smooth[-1], smooth, smooth[0]],
                          height=min_share * smooth.max(), distance=2)
    peaks = [p - 1 for p in peaks if 0 <= p - 1 < bins]
    centers = 0.5 * (edges[:-1] + edges[1:])
    return sorted(float(centers[p]) for p in peaks), horizontal


def plane_offsets(values, thickness, min_points, peak_ratio):
    if len(values) < min_points:
        return []
    width = thickness / 2.0
    pad = 4 * thickness
    low, high = values.min() - pad, values.max() + pad
    counts, edges = np.histogram(
        values, bins=max(int(np.ceil((high - low) / width)), 8),
        range=(low, high))
    window = max(int(round(thickness / width)), 1)
    smooth = np.convolve(counts.astype(float), np.ones(2 * window + 1),
                         mode="same")
    if smooth.max() <= 0:
        return []

    floor_value = max(min_points, peak_ratio * smooth.max())
    peaks, _ = find_peaks(smooth, height=floor_value,
                          prominence=0.25 * floor_value,
                          distance=max(int(round(2 * thickness / width)), 1))
    centers = 0.5 * (edges[:-1] + edges[1:])

    out = []
    for peak in peaks:
        offset = centers[peak]
        for _ in range(4):
            near = np.abs(values - offset) <= thickness
            if np.count_nonzero(near) < min_points:
                break
            offset = float(np.median(values[near]))
        near = np.abs(values - offset) <= thickness
        if np.count_nonzero(near) >= min_points:
            out.append((offset, int(np.count_nonzero(near))))
    return out


def facade_lines(points, normals, thickness, min_points, peak_ratio,
                 vertical_angle, angle_bins, angle_share, angle_tol,
                 max_lines):
    """Return [(unit normal in plan, offset, support)] for the facades."""
    angles, horizontal = facade_directions(normals, vertical_angle,
                                           angle_bins, angle_share)
    if not angles:
        return []

    flat_points = points[horizontal][:, :2]
    flat_normals = normals[horizontal][:, :2]
    length = np.linalg.norm(flat_normals, axis=1, keepdims=True)
    length[length == 0] = 1.0
    flat_normals = flat_normals / length

    limit = np.cos(np.deg2rad(angle_tol))
    lines = []
    for angle in angles:
        direction = np.array([np.cos(np.deg2rad(angle)),
                              np.sin(np.deg2rad(angle))])
        aligned = np.abs(flat_normals @ direction) >= limit
        chosen = flat_points[aligned]
        if len(chosen) < min_points:
            continue
        for offset, support in plane_offsets(chosen @ direction, thickness,
                                             min_points, peak_ratio):
            lines.append((direction, offset, support))

    lines.sort(key=lambda item: -item[2])
    return lines[:max_lines]


