def arrangement(lines, bounds, margin):
    xmin, ymin, xmax, ymax = bounds
    frame = box(xmin - margin, ymin - margin, xmax + margin, ymax + margin)
    reach = 2.0 * (abs(xmax - xmin) + abs(ymax - ymin))

    segments = [LineString(frame.exterior.coords)]
    for direction, offset, _ in lines:
        along = np.array([-direction[1], direction[0]])
        middle = direction * offset
        segments.append(LineString([tuple(middle - along * reach),
                                    tuple(middle + along * reach)]))

    noded = unary_union(segments)
    faces = [f for f in polygonize(noded) if f.is_valid and not f.is_empty]
    return faces


def occupancy_grid(points, cell, min_hits, percentile):
    x0, y0 = points[:, 0].min(), points[:, 1].min()
    ix = np.floor((points[:, 0] - x0) / cell).astype(int)
    iy = np.floor((points[:, 1] - y0) / cell).astype(int)
    shape = (int(ix.max()) + 1, int(iy.max()) + 1)

    counts = np.zeros(shape, dtype=np.int32)
    np.add.at(counts, (ix, iy), 1)

    heights = np.zeros(shape)
    flat = ix * shape[1] + iy
    order = np.lexsort((points[:, 2], flat))
    flat, z = flat[order], points[order, 2]
    breaks = np.r_[0, np.flatnonzero(np.diff(flat)) + 1, len(flat)]
    for start, stop in zip(breaks[:-1], breaks[1:]):
        key = flat[start]
        heights[key // shape[1], key % shape[1]] = \
            np.percentile(z[start:stop], percentile)

    mask = counts >= min_hits
    centres, values = [], []
    for i, j in zip(*np.nonzero(mask)):
        centres.append(((i + 0.5) * cell + x0, (j + 0.5) * cell + y0))
        values.append(heights[i, j])
    return np.array(centres), np.array(values)


def label_faces(faces, centres, values, cell, min_fill, min_area,
                cell_percentile):
    """Decide which arrangement cells are inside the building, and how tall."""
    tree = STRtree([Point(p) for p in centres])
    inside, heights = [], []

    for face in faces:
        if face.area < min_area:
            inside.append(False)
            heights.append(0.0)
            continue

        hits = tree.query(face)
        if len(hits):
            keep = [k for k in hits if face.contains(Point(centres[k]))]
        else:
            keep = []

        covered = len(keep) * cell * cell
        fill = covered / face.area
        if fill < min_fill or len(keep) < 2:
            inside.append(False)
            heights.append(0.0)
        else:
            # median, not a high percentile: a cell touching the tower would
            # otherwise inherit the tower's height from a few boundary cells
            inside.append(True)
            heights.append(float(np.percentile(values[keep],
                                               cell_percentile)))
    return np.array(inside), np.array(heights)


def quantize_heights(heights, inside, count, tolerance):
    live = heights[inside]
    if live.size == 0:
        raise SystemExit("no arrangement cell is inside the building")

    counts, edges = np.histogram(live, bins=60)
    centers = 0.5 * (edges[:-1] + edges[1:])
    peaks, _ = find_peaks(np.r_[0, counts, 0], distance=2)
    peaks = [p - 1 for p in peaks if 0 <= p - 1 < len(centers)]
    peaks.sort(key=lambda p: -counts[p])

    levels = sorted(float(centers[p]) for p in peaks[:count])
    if not levels:
        levels = [float(np.median(live))]
    if live.max() - max(levels) > tolerance:
        levels.append(float(live.max()))

    snapped = heights.copy()
    for index in np.flatnonzero(inside):
        nearest = min(levels, key=lambda v: abs(v - heights[index]))
        if abs(nearest - heights[index]) <= tolerance:
            snapped[index] = nearest
        else:
            levels.append(float(heights[index]))
            snapped[index] = heights[index]
    return snapped, sorted(set(round(v, 3) for v in levels))


