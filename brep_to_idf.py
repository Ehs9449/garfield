def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--envelope", required=True)
    parser.add_argument("--windows", default=None)
    parser.add_argument("--columns", default=None)
    parser.add_argument("--dirs", default=None)
    parser.add_argument("--out", default="building.idf")
    parser.add_argument("--height", type=float, required=True)

    parser.add_argument("--plane-thickness", type=float, default=0.5,
                        help="facade plane slab half width, metres")
    parser.add_argument("--plane-min-points", type=int, default=400)
    parser.add_argument("--plane-peak-ratio", type=float, default=0.04)
    parser.add_argument("--max-lines", type=int, default=20,
                        help="how many facade lines enter the arrangement")
    parser.add_argument("--vertical-angle", type=float, default=25.0)
    parser.add_argument("--angle-bins", type=int, default=90)
    parser.add_argument("--angle-share", type=float, default=0.25)
    parser.add_argument("--angle-tol", type=float, default=15.0)

    parser.add_argument("--cell", type=float, default=0.6,
                        help="occupancy sampling cell, metres")
    parser.add_argument("--min-hits", type=int, default=4)
    parser.add_argument("--min-fill", type=float, default=0.35,
                        help="share of a cell that must hold points")
    parser.add_argument("--min-cell-area", type=float, default=1.0)
    parser.add_argument("--top-percentile", type=float, default=95.0,
                        help="top of the envelope inside one sampling cell")
    parser.add_argument("--cell-percentile", type=float, default=50.0,
                        help="height of an arrangement cell, across its "
                             "sampling cells. Keep this near 50")
    parser.add_argument("--levels", type=int, default=4)
    parser.add_argument("--level-tolerance", type=float, default=3.0)

    parser.add_argument("--window-band", type=float, default=1.2)
    parser.add_argument("--window-cell", type=float, default=0.25)
    parser.add_argument("--window-margin", type=float, default=0.15)
    parser.add_argument("--window-min-size", type=float, default=0.5)
    parser.add_argument("--window-min-points", type=int, default=25)
    parser.add_argument("--window-reach", type=float, default=0.5,
                        help="slack on the wall rectangle, metres")
    parser.add_argument("--orphans", default=None,
                        help="write the glazing points that found no wall, "
                             "e.g. --orphans orphans.ply")

    parser.add_argument("--column-eps", type=float, default=0.5)
    parser.add_argument("--column-min-points", type=int, default=60)
    parser.add_argument("--column-min-height", type=float, default=2.0)
    parser.add_argument("--column-max-width", type=float, default=2.5)
    parser.add_argument("--column-slenderness", type=float, default=1.5)

    parser.add_argument("--preview", default=None)
    parser.add_argument("--preview-cloud", default=None)
    parser.add_argument("--zone", default="Zone_Building")
    parser.add_argument("--name", default="LSU Tower")
    parser.add_argument("--version", default="24.1")
    args = parser.parse_args()

    envelope = load_points(args.envelope)
    glazing = load_points(args.windows)
    columns = load_points(args.columns)
    if len(envelope) == 0:
        raise SystemExit(f"no points in {args.envelope}")
    print(f"envelope {len(envelope)}  windows {len(glazing)}  "
          f"columns {len(columns)}")

    rotation, north = building_frame(read_directions(args.dirs), envelope)
    envelope = envelope @ rotation.T
    glazing = glazing @ rotation.T if len(glazing) else glazing
    columns = columns @ rotation.T if len(columns) else columns

    span = envelope[:, 2].max() - envelope[:, 2].min()
    scale = args.height / span
    origin = np.array([envelope[:, 0].min(), envelope[:, 1].min(),
                       envelope[:, 2].min()])
    envelope = (envelope - origin) * scale
    glazing = (glazing - origin) * scale if len(glazing) else glazing
    columns = (columns - origin) * scale if len(columns) else columns
    print(f"north axis {north:.2f} deg, scale {scale:.3f} "
          f"(height {args.height:.1f} m)")

    facade_points = envelope if len(glazing) == 0 else \
        np.vstack([envelope, glazing])

    spacing = args.cell / 3.0
    normals = estimate_normals(facade_points, radius=max(spacing, 0.25) * 3)

    lines = facade_lines(facade_points, normals, args.plane_thickness,
                         args.plane_min_points, args.plane_peak_ratio,
                         args.vertical_angle, args.angle_bins,
                         args.angle_share, args.angle_tol, args.max_lines)
    print(f"facade lines {len(lines)}")
    if len(lines) < 4:
        raise SystemExit("too few facade planes - lower --plane-min-points "
                         "or --plane-peak-ratio")

    bounds = (facade_points[:, 0].min(), facade_points[:, 1].min(),
              facade_points[:, 0].max(), facade_points[:, 1].max())
    faces = arrangement(lines, bounds, margin=2.0)
    print(f"arrangement cells {len(faces)}")

    centres, values = occupancy_grid(facade_points, args.cell, args.min_hits,
                                     args.top_percentile)
    inside, heights = label_faces(faces, centres, values, args.cell,
                                  args.min_fill, args.min_cell_area,
                                  args.cell_percentile)
    heights, levels = quantize_heights(heights, inside, args.levels,
                                       args.level_tolerance)
    footprint = sum(f.area for f, keep in zip(faces, inside) if keep)
    print(f"inside cells {int(inside.sum())}, footprint {footprint:.0f} m2")
    print(f"levels {[round(v, 1) for v in levels]} m")

    surfaces = extrude(faces, inside, heights)
    walls = [s for s in surfaces if s["type"] == "Wall"]
    for wall in walls:
        wall["frame"] = wall_frame(wall)

    area, imbalance, volume = closure_report(surfaces)
    print(f"surfaces {len(surfaces)} ({len(walls)} wall, "
          f"{sum(1 for s in surfaces if s['type'] == 'Roof')} roof, "
          f"{sum(1 for s in surfaces if s['type'] == 'Floor')} floor)")
    print(f"total area {area:.1f} m2, volume {volume:.1f} m3")
    closed = imbalance < 1e-6 * max(area, 1.0)
    print(f"closure error {imbalance:.6f} m2 "
          f"({'closed' if closed else 'NOT CLOSED'})")

    placed, report = windows_on_walls(glazing, walls, args.window_band,
                                      args.window_cell, args.window_margin,
                                      args.window_min_size,
                                      args.window_min_points,
                                      args.window_reach)
    share = 100.0 * report["unassigned"] / max(len(glazing), 1)
    hosts = len({w["wall"] for w in placed})
    print(f"windows {len(placed)} placed on {hosts} of {len(walls)} walls "
          f"({report['unassigned']} points, {share:.0f}%, found no wall)")
    if args.orphans and len(report["unassigned_points"]):
        write_scaled_cloud(args.orphans,
                           {"window": report["unassigned_points"]})
        print(f"  wrote {args.orphans}")

    shades, rejected, measured = column_shades(
        columns, args.column_eps, args.column_min_points,
        args.column_min_height, args.column_max_width,
        args.column_slenderness)
    print(f"columns {len(shades) // 4} kept -> {len(shades)} shading surfaces"
          + (f" (rejected {rejected['too_short']} short, "
             f"{rejected['too_wide']} wide, {rejected['too_fat']} fat)"
             if sum(rejected.values()) else ""))
    if measured:
        tall = np.array([m[0] for m in measured])
        wide = np.array([m[1] for m in measured])
        print(f"  cluster heights m: min {tall.min():.1f}  "
              f"median {np.median(tall):.1f}  max {tall.max():.1f}"
              f"   (--column-min-height {args.column_min_height})")
        print(f"  cluster widths  m: min {wide.min():.1f}  "
              f"median {np.median(wide):.1f}  max {wide.max():.1f}"
              f"   (--column-max-width {args.column_max_width})")

    write_idf(args.out, surfaces, placed, shades, args.zone, north,
              args.version, args.name)
    print(f"\nwrote {args.out}")
    if args.preview:
        write_preview(args.preview, surfaces, placed, shades)
        print(f"wrote {args.preview}")
    if args.preview_cloud:
        write_scaled_cloud(args.preview_cloud,
                           {"envelope": envelope, "window": glazing,
                            "column": columns})
        print(f"wrote {args.preview_cloud}")


if __name__ == "__main__":
    main()
