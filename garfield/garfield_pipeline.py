import typing
from dataclasses import dataclass, field
from typing import Literal, Type, Mapping, Any

import torch
from nerfstudio.pipelines.base_pipeline import VanillaPipeline, VanillaPipelineConfig
from torch.cuda.amp.grad_scaler import GradScaler

import tqdm

from sklearn.preprocessing import QuantileTransformer
from garfield.garfield_datamanager import GarfieldDataManagerConfig, GarfieldDataManager
from garfield.garfield_model import GarfieldModel, GarfieldModelConfig

@dataclass
class GarfieldPipelineConfig(VanillaPipelineConfig):
    """Configuration for GARField pipeline instantiation"""

    _target: Type = field(default_factory=lambda: GarfieldPipeline)
    """target class to instantiate"""

    datamanager: GarfieldDataManagerConfig = field(default_factory=lambda: GarfieldDataManagerConfig())
    model: GarfieldModelConfig = field(default_factory=lambda: GarfieldModelConfig())

    start_grouping_step: int = 2000
    max_grouping_scale: float = 2.0
    num_rays_per_image: int = 256
    normalize_grouping_scale: bool = True

class GarfieldPipeline(VanillaPipeline):
    config: GarfieldPipelineConfig
    datamanager: GarfieldDataManager
    model: GarfieldModel

    def __init__(
        self,
        config: GarfieldPipelineConfig,
        device: str,
        test_mode: Literal["test", "val", "inference"] = "val",
        world_size: int = 1,
        local_rank: int = 0,
        grad_scaler: typing.Optional[GradScaler] = None,
    ):
        config.model.max_grouping_scale = config.max_grouping_scale
        super().__init__(
            config,
            device,
            test_mode,
            world_size,
            local_rank,
            grad_scaler,
        )

    def get_train_loss_dict(self, step: int):
        """In addition to the base class, we also calculate SAM masks
        and their 3D scales at `start_grouping_step`."""
        if step == self.config.start_grouping_step:
            loaded = self.datamanager.load_sam_data()
            if not loaded:
                self.populate_grouping_info()
            else:
                # Initialize grouping statistics. This will be automatically loaded from a checkpoint next time.
                scale_stats = self.datamanager.scale_3d_statistics
                self.grouping_stats = torch.nn.Parameter(scale_stats)
                self.model.grouping_field.quantile_transformer = (
                    self._get_quantile_func(scale_stats)
                )
            # Set the number of rays per image to the number of rays per image for grouping
            pixel_sampler = self.datamanager.train_pixel_sampler
            pixel_sampler.num_rays_per_image = pixel_sampler.config.num_rays_per_image

        ray_bundle, batch = self.datamanager.next_train(step)
        if step >= self.config.start_grouping_step:
            # also set the grouping info in the batch; in-place operation
            self.datamanager.next_group(ray_bundle, batch)

        model_outputs = self._model(
            ray_bundle
        )  # train distributed data parallel model if world_size > 1

        metrics_dict = self.model.get_metrics_dict(model_outputs, batch)
        loss_dict = self.model.get_loss_dict(model_outputs, batch, metrics_dict)
        if step >= self.config.start_grouping_step:
            loss_dict.update(
                self.model.get_loss_dict_group(model_outputs, batch, metrics_dict)
            )

        return model_outputs, loss_dict, metrics_dict

    def populate_grouping_info(self, chunk_size=1, max_sampled_scales=100000, sample_per_image=200):
        """
        Memory-safe streaming version:
        - computes per-image pixel_level_keys, scale_3d, group_cdf
        - saves each image's results to disk as compressed npz via datamanager.save_sam_data_single()
        - accumulates a limited random sample of scale values to compute grouping_stats (quantiles)
        - DOES NOT build giant nested tensors for all images at once
        """
        import os
        import numpy as np
        import torch
        from tqdm import trange

        self.model.eval()

        train_cameras = self.datamanager.train_dataset.cameras
        n = len(train_cameras)
        sampled_scales = []
        total_saved = 0

        # --------------------------------------------------
        # Determine the active dataset from the actual
        # Nerfstudio training-image paths.
        #
        # Example:
        # /home/eaghae1/data/towerlsu/images/frame.jpg
        #                    -> towerlsu
        # --------------------------------------------------

        first_image_path = os.path.abspath(
            str(self.datamanager.train_dataset.image_filenames[0])
        )

        images_dir = os.path.dirname(first_image_path)
        dataset_root = os.path.dirname(images_dir)
        dataset_name = os.path.basename(dataset_root)

        # --------------------------------------------------
        # Precomputed SAM3 masks generated by the pipeline
        # --------------------------------------------------

        sam3_mask_dir = os.path.abspath(
            os.path.join(
                "outputs",
                dataset_name,
                "garfield_training_masks_sam3",
            )
        )

        self.datamanager.img_group_model.config.sam3_mask_dir = (
            sam3_mask_dir
        )

        print(
            f"[SAM3] Dataset: {dataset_name}"
        )
        print(
            f"[SAM3] Precomputed mask directory: {sam3_mask_dir}"
        )

        # --------------------------------------------------
        # Model-specific GARField grouping cache
        # --------------------------------------------------

        cache_dir = os.path.join(
            dataset_root,
            f"sam_cache_{self.datamanager.img_group_model.config.model_type}",
        )

        self.datamanager.sam_cache_dir = cache_dir

        os.makedirs(
            self.datamanager.sam_cache_dir,
            exist_ok=True,
        )

        print(
            f"[GARField] Group cache directory: {cache_dir}"
        )

        for i in trange(n, desc="Calculating 3D masks"):
            # generate rays for camera i
            camera_ray_bundle = train_cameras.generate_rays(camera_indices=i).to(self.device)
            with torch.no_grad():
                outputs = self.model.get_outputs_for_camera_ray_bundle(camera_ray_bundle)

            rgb = self.datamanager.train_dataset[i]["image"]
            depth = outputs["depth"]
            points = camera_ray_bundle.origins + camera_ray_bundle.directions * depth

            image_name = os.path.basename(
                str(self.datamanager.train_dataset.image_filenames[i])
            )

            pixel_level_keys, scale_3d, group_cdf = self.datamanager._calculate_3d_groups(
                rgb,
                depth,
                points,
                max_scale=self.config.max_grouping_scale,
                image_name=image_name,
            )

            # save the per-image data immediately to disk
            self.datamanager.save_sam_data_single(i, pixel_level_keys, scale_3d, group_cdf)

            # sample scales for global quantile estimation (avoid using all values)
            try:
                flat = scale_3d.flatten().detach().cpu().numpy()
            except Exception:
                flat = scale_3d.flatten().cpu().numpy()
            # filter valid range
            mask = (flat > 0) & (flat < self.config.max_grouping_scale)
            flat = flat[mask]
            if flat.size > 0:
                if flat.size <= sample_per_image:
                    chosen = flat
                else:
                    # random sample without replacement
                    idx = np.random.choice(flat.size, size=sample_per_image, replace=False)
                    chosen = flat[idx]
                sampled_scales.append(chosen)
                total_saved += chosen.size

                # keep sampled_scales bounded by max_sampled_scales
                if total_saved > max_sampled_scales:
                    # trim older samples down proportionally
                    concatenated = np.concatenate(sampled_scales)
                    # keep only last max_sampled_scales samples randomly
                    if concatenated.size > max_sampled_scales:
                        keep_idx = np.random.choice(concatenated.size, size=max_sampled_scales, replace=False)
                        concatenated = concatenated[keep_idx]
                    sampled_scales = [concatenated]
                    total_saved = concatenated.size

            # clear GPU caches and local refs to be safe
            try:
                del outputs, depth, points, pixel_level_keys, scale_3d, group_cdf
            except Exception:
                pass
            torch.cuda.empty_cache()

        # done loop: build grouping_stats from sampled_scales
        if len(sampled_scales) == 0:
            # fallback: empty
            grouping_stats_tensor = torch.zeros(0).to(self.device)
        else:
            import numpy as np
            concat = np.concatenate(sampled_scales)
            grouping_stats_tensor = torch.from_numpy(concat).float().to(self.device)

        # Save a small metadata index so datamanager knows where files are
        self.datamanager.save_sam_index()

        # set small sampled grouping stats for quantile transformer
        self.grouping_stats = torch.nn.Parameter(grouping_stats_tensor)
        self.model.grouping_field.quantile_transformer = self._get_quantile_func(grouping_stats_tensor)

        # Set datamanager to lazy load from saved files (datamanager should implement loading)
        self.datamanager.load_sam_data_lazy()

        # Turn model back to train mode
        self.model.train()


    def load_state_dict(self, state_dict: Mapping[str, Any], strict: bool = True):
        """
        Same as the base class, but also loads the grouping statistics.
        It's important to normalize the 3D scales as input to the grouping field.
        """
        # Load 3D group scale statistics
        grouping_stats = state_dict["grouping_stats"]
        self.grouping_stats = torch.nn.Parameter(torch.zeros_like(grouping_stats)).to(
            self.device
        )
        # Calculate quantile transformer
        self.model.grouping_field.quantile_transformer = self._get_quantile_func(
            grouping_stats
        )

        return super().load_state_dict(state_dict, strict)

    def _get_quantile_func(self, scales: torch.Tensor, distribution="normal"):
        """
        Use 3D scale statistics to normalize scales -- use quantile transformer.
        """
        scales = scales.flatten()
        scales = scales[(scales > 0) & (scales < self.config.max_grouping_scale)]

        scales = scales.detach().cpu().numpy()

        # Calculate quantile transformer
        quantile_transformer = QuantileTransformer(output_distribution=distribution)
        quantile_transformer = quantile_transformer.fit(scales.reshape(-1, 1))

        def quantile_transformer_func(scales):
            # This function acts as a wrapper for QuantileTransformer.
            # QuantileTransformer expects a numpy array, while we have a torch tensor.
            return torch.Tensor(
                quantile_transformer.transform(scales.cpu().numpy())
            ).to(scales.device)

        return quantile_transformer_func
